class ProductOfNumbers {
    List<Integer> list;

    public ProductOfNumbers() {
        list = new ArrayList<>();
    }
    
    public void add(int num) {
        list.add(num);
    }
    
    public int getProduct(int k) {
        int p = 1;
        int idx = list.size()-1;
        for(int i = 0; i<k; i++){
            if(idx < 0) break;
            p *= list.get(idx--);
        }
        return p;
    }
}

